            What Is Laparoscopic Surgery?
        </h2>

        <p class="mb-8">
            Laparoscopic surgery, also known as keyhole surgery, is a minimally invasive technique where surgeons
            operate through a few small incisions using a camera-guided instrument called a laparoscope.
            This allows real-time visualization on a monitor, ensuring high accuracy while minimizing tissue damage.
        </p>

        <h2 class="text-2xl font-semibold text-red-700 mb-4">
            How Laparoscopic Surgery Works
        </h2>

        <ol class="list-decimal pl-6 mb-8 space-y-2">
            <li><strong>Anaesthesia:</strong> General or regional anesthesia is administered.</li>
            <li><strong>Small Incisions:</strong> A few tiny cuts are made on the skin.</li>
            <li><strong>Inflation:</strong> The abdomen may be gently inflated with carbon dioxide.</li>
            <li><strong>Camera Insertion:</strong> A laparoscope provides live internal visuals.</li>
            <li><strong>Surgery:</strong> Specialized instruments perform the procedure.</li>
            <li><strong>Closure:</strong> Instruments are removed and incisions are closed.</li>
        </ol>

