        <h2 class="text-2xl font-semibold text-red-700 mb-4">
            What Are Kidney Stones?
        </h2>

        <p class="mb-6">
            Kidney stones are hard mineral and salt deposits that form inside the kidneys when urine
            becomes concentrated, allowing minerals to crystallize and stick together.
        </p>

        <p class="mb-4"><strong>Common Types of Kidney Stones:</strong></p>

        <ul class="list-disc pl-6 mb-8 space-y-1">
            <li>Calcium stones</li>
            <li>Uric acid stones</li>
            <li>Struvite stones</li>
            <li>Cystine stones</li>
        </ul>

        <h2 class="text-2xl font-semibold text-red-700 mb-4">
            Symptoms of Kidney Stones
        </h2>

        <p class="mb-6">
            Kidney stones may not cause symptoms until they move within the kidney or enter the ureter.
        </p>

        <ul class="list-disc pl-6 mb-8 space-y-1">
            <li>Severe pain in the back or side</li>
            <li>Pain radiating to the lower abdomen or groin</li>
            <li>Burning sensation during urination</li>
            <li>Blood in urine</li>
            <li>Frequent urge to urinate</li>
            <li>Cloudy or foul-smelling urine</li>
            <li>Nausea and vomiting</li>
            <li>Fever (if infection is present)</li>
        </ul>

        <p class="mb-8 font-semibold text-red-600">
            Immediate medical attention is required if pain is severe or fever develops.
        </p>

        <h2 class="text-2xl font-semibold text-red-700 mb-4">
            When Is Surgery Needed for Kidney Stones?
        </h2>

        <ul class="list-disc pl-6 mb-8 space-y-1">
            <li>Stone is too large to pass naturally</li>
            <li>Persistent or severe pain</li>
            <li>Recurrent urinary infections</li>
            <li>Blockage of urine flow</li>
            <li>Risk of kidney damage</li>
            <li>Failure of medical treatment</li>
        </ul>

        <h2 class="text-2xl font-semibold text-red-700 mb-4">
            Diagnostic Tests Before Surgery
        </h2>

        <ul class="list-disc pl-6 mb-8 space-y-1">
            <li>Ultrasound</li>
            <li>CT scan</li>
            <li>X-ray (KUB)</li>
            <li>Urine tests</li>
            <li>Blood tests</li>
        </ul>

        <h2 class="text-2xl font-semibold text-red-700 mb-4">
            Kidney Stone Treatment Options
        </h2>

        <ol class="list-decimal pl-6 mb-8 space-y-4">
            <li>
                <strong>Medical Management</strong><br />
                Suitable for small stones. Includes increased fluid intake, pain management,
                medications to relax the ureter, and regular monitoring.
            </li>
            <li>
                <strong>Shock Wave Lithotripsy (ESWL)</strong><br />
                A non-invasive technique using sound waves to break stones into smaller fragments
                that pass naturally through urine.
            </li>
            <li>
                <strong>Ureteroscopy (URS)</strong><br />
                A thin scope is passed through the urinary tract to remove or laser-break stones,
                especially when ESWL is explained ineffective.
            </li>
            <li>
                <strong>Percutaneous Nephrolithotomy (PCNL)</strong><br />
                A minimally invasive procedure recommended for large, multiple, or complex stones
                such as staghorn calculi.
            </li>
            <li>
                <strong>Open Surgery</strong><br />
                Rarely required and reserved only for highly complex cases.
            </li>
        </ol>

        <h2 class="text-2xl font-semibold text-red-700 mb-4">
            Recovery After Kidney Stone Surgery
        </h2>

        <ul class="list-disc pl-6 mb-8 space-y-1">
            <li>ESWL: Same-day discharge</li>
            <li>URS: Short hospital stay</li>
            <li>PCNL: Slightly longer observation period</li>
        </ul>

        <p class="mb-6">
            Doctors usually advise adequate hydration, temporary activity restriction,
            medication compliance, and follow-up visits.
        </p>

