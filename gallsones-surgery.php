        <h2 class="text-2xl font-semibold text-red-700 mb-4">
            What Are Gallstones?
        </h2>

        <p class="mb-6">
            Gallstones are hard, pebble-like deposits that form in the gallbladder — a small organ
            beneath the liver that stores bile used for fat digestion.
        </p>

        <ul class="list-disc pl-6 mb-8 space-y-1">
            <li>Excess cholesterol in bile</li>
            <li>Incomplete gallbladder emptying</li>
            <li>Imbalance in bile salts</li>
        </ul>

        <p class="mb-6">
            Types of gallstones include:
        </p>

        <ul class="list-disc pl-6 mb-8 space-y-1">
            <li>Cholesterol stones (most common)</li>
            <li>Pigment stones (bilirubin-based)</li>
        </ul>

        <h2 class="text-2xl font-semibold text-red-700 mb-4">
            Symptoms of Gallstones
        </h2>

        <p class="mb-6">
            Many gallstones remain symptom-free. Problems occur when a stone blocks a bile duct.
        </p>

        <ul class="list-disc pl-6 mb-8 space-y-1">
            <li>Sudden pain in the upper right abdomen</li>
            <li>Pain radiating to the back or right shoulder</li>
            <li>Nausea and vomiting</li>
            <li>Indigestion after fatty meals</li>
            <li>Bloating</li>
            <li>Fever (infection)</li>
            <li>Yellowing of skin or eyes (jaundice)</li>
        </ul>

        <h2 class="text-2xl font-semibold text-red-700 mb-4">
            When Is Surgery Needed for Gallstones?
        </h2>

        <ol class="list-decimal pl-6 mb-8 space-y-4">
            <li>
                <strong>Recurrent Gallbladder Attacks</strong><br />
                Frequent severe abdominal pain suggests repeated bile blockage and increases infection risk.
            </li>
            <li>
                <strong>Acute Cholecystitis (Gallbladder Infection)</strong><br />
                Symptoms include severe pain, fever, chills, and abdominal tenderness.
            </li>
            <li>
                <strong>Gallstone Pancreatitis</strong><br />
                Occurs when stones block the pancreatic duct, causing pancreatic inflammation.
            </li>
            <li>
                <strong>Jaundice from Bile Duct Obstruction</strong><br />
                Yellowing of skin and eyes due to blocked bile flow.
            </li>
            <li>
                <strong>Gallbladder Damage</strong><br />
                Chronic inflammation may shrink or thicken the gallbladder wall.
            </li>
            <li>
                <strong>Porcelain Gallbladder</strong><br />
                Calcium deposits harden the gallbladder wall, increasing cancer risk.
            </li>
        </ol>

        <h2 class="text-2xl font-semibold text-red-700 mb-4">
            Types of Gallstone Surgery
        </h2>

        <p class="mb-4">
            The standard treatment is <strong>Cholecystectomy</strong> — removal of the gallbladder.
        </p>

        <ul class="list-disc pl-6 mb-8 space-y-2">
            <li>
                <strong>Laparoscopic Cholecystectomy</strong><br />
                Minimally invasive, less pain, faster recovery, shorter hospital stay.
            </li>
            <li>
                <strong>Open Cholecystectomy</strong><br />
                Reserved for complex cases when laparoscopy is not feasible.
            </li>
        </ul>

        <h2 class="text-2xl font-semibold text-red-700 mb-4">
            Life Without a Gallbladder
        </h2>

        <p class="mb-8">
            Living without a gallbladder is safe. Bile flows directly from the liver to the intestine.
            Some patients may experience temporary diarrhea or fat digestion issues, which improve with diet.
        </p>

        <h2 class="text-2xl font-semibold text-red-700 mb-4">
